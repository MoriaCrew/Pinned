/**
 * BoardRepository port (PIN-62, docs/11 §5.4). The in-memory
 * implementation below is the test double and the contract; the
 * Firestore implementation (PIN-53a-fs) must pass the same suite
 * (`board-repository.contract.ts`).
 *
 * Contract highlights every implementation must keep:
 * - Reads return isolated copies; writes store copies.
 * - Duplicate creates and references to a missing board/element
 *   throw RangeError (same convention as GameRepository).
 * - Board.counters are maintained by the repository on every
 *   mutation (see BoardCounters for what each counter means);
 *   counter-only updates do not bump Board.version.
 * - `createElement` appends `element_added`; a pin becoming
 *   "pinned" (on create or via setPinStatus) appends `pin_added`
 *   exactly once. Repository-emitted event ids are generated by
 *   the repository: non-empty and unique per board.
 * - Events are append-only: no update/delete, duplicate event ids
 *   throw. Lists are createdAt-ascending; ties keep append order.
 * - deleteElement cascades atomically: the element and all its
 *   pins are removed, scenes that used it get `hidden: true`, and
 *   counters follow. Deleting a missing element is a no-op result,
 *   not an error (idempotent for the PIN-56 endpoint).
 * - One pin per (boardId, elementId): the board grid is a set of
 *   elements. Re-pinning after deletePin works.
 * - Reclaim-attempt counters (PIN-90) are keyed by an opaque caller
 *   hash; `mutateReclaimAttempt` applies the transform atomically
 *   (transactional in Firestore) so concurrent failures across
 *   instances cannot lose increments. Returning null clears.
 * - The participant cap (PIN-91) is enforced inside
 *   `createParticipantIfBelowCap`, never by a caller's
 *   read-then-write: in Firestore the check reads the board doc's
 *   participantCount and the create increments that same doc in
 *   one transaction, so concurrent joins serialize on it (a
 *   participants-collection count would be a phantom read). A
 *   refused create writes nothing — no participant, no counter,
 *   no event. Join-rate counters (PIN-91) work like the reclaim
 *   counters: `tryRecordJoin` checks and increments atomically,
 *   and a denied join records nothing.
 */
import type {
  Board,
  BoardCounters,
  BoardEvent,
  Element,
  Participant,
  Pin,
  PinStatus,
  Scene,
} from "./board";
import { decideJoin, type JoinAttemptState, type JoinRateParams } from "./join-rate";
import type { ReclaimAttemptState } from "./reclaim-lockout";

export interface DeleteElementResult {
  deleted: boolean;
  removedPinIds: string[];
  hiddenSceneIds: string[];
}

export interface BoardRepository {
  createBoard(board: Board): Promise<void>;
  getBoard(slug: string): Promise<Board | null>;

  /**
   * Upsert join identity; participantCount grows only on first
   * insert, which also appends `participant_joined` (PIN-74).
   */
  putParticipant(participant: Participant): Promise<void>;
  /**
   * Atomically create `participant` only if the board roster is
   * below `cap` (PIN-91). Returns false — writing nothing — when
   * the participant is new and the roster is already at cap. An
   * existing participant id upserts like putParticipant and
   * returns true: roster members are never cap-blocked.
   */
  createParticipantIfBelowCap(participant: Participant, cap: number): Promise<boolean>;
  /**
   * Atomically record one new-participant creation against an
   * opaque key (PIN-91): true consumes one unit of the fixed-
   * window budget; false means the budget is spent and nothing
   * was recorded, so retries cannot extend the window.
   */
  tryRecordJoin(
    boardId: string,
    key: string,
    now: number,
    params: JoinRateParams,
  ): Promise<boolean>;
  getParticipant(boardId: string, participantId: string): Promise<Participant | null>;
  listParticipants(boardId: string): Promise<Participant[]>;

  /** Reclaim-PIN failure counter for an opaque key (PIN-90). */
  getReclaimAttempt(boardId: string, key: string): Promise<ReclaimAttemptState | null>;
  /**
   * Atomically transform the counter for `key`: fn receives an
   * isolated copy (or null) and returns the next state, or null to
   * clear it. Returns the stored state (isolated copy) or null.
   */
  mutateReclaimAttempt(
    boardId: string,
    key: string,
    fn: (current: ReclaimAttemptState | null) => ReclaimAttemptState | null,
  ): Promise<ReclaimAttemptState | null>;

  /** Stores the element and appends `element_added` (actor = ownerId). */
  createElement(element: Element): Promise<void>;
  getElement(elementId: string): Promise<Element | null>;
  listElements(boardId: string): Promise<Element[]>;
  listElementsByOwner(boardId: string, ownerId: string): Promise<Element[]>;
  /**
   * Library copies made from a source element (PIN-85), across
   * all boards, createdAt-ascending. Empty for a native element
   * nobody copied. Backs the shared-asset delete guard.
   */
  listElementsBySource(sourceElementId: string): Promise<Element[]>;
  /**
   * Elements referencing a cutout object, across all boards
   * (PIN-85). Library copies share their source's refs verbatim,
   * so this is the exact "who still needs these bytes" set the
   * delete guard consults — immune to copy-chain shape.
   */
  listElementsByCutoutRef(cutoutRef: string): Promise<Element[]>;
  /** Cascade delete; see the contract notes above. */
  deleteElement(elementId: string): Promise<DeleteElementResult>;

  /** Stores the pin; appends `pin_added` when created already pinned. */
  createPin(pin: Pin): Promise<void>;
  getPin(pinId: string): Promise<Pin | null>;
  listPins(boardId: string, status?: PinStatus): Promise<Pin[]>;
  listPinsForElement(elementId: string): Promise<Pin[]>;
  /**
   * Transition a pin. `now` timestamps the `pin_added` event a
   * candidate→pinned transition emits. Missing pin → null; a
   * no-op transition returns the pin unchanged.
   */
  setPinStatus(pinId: string, status: PinStatus, now: number): Promise<Pin | null>;
  deletePin(pinId: string): Promise<boolean>;

  /** Upsert; sceneCount tracks non-hidden scenes. */
  putScene(scene: Scene): Promise<void>;
  getScene(sceneId: string): Promise<Scene | null>;
  listScenes(boardId: string, opts?: { includeHidden?: boolean }): Promise<Scene[]>;

  /** For scene_* producers; element/pin events are repo-emitted. */
  appendEvent(event: BoardEvent): Promise<void>;
  /** Chronological; `limit` keeps the most recent events. */
  listEvents(boardId: string, opts?: { limit?: number }): Promise<BoardEvent[]>;
}

function clone<T>(value: T): T {
  return structuredClone(value);
}

/** createdAt-ascending; Array.sort is stable, so ties keep insertion order. */
function byCreatedAt<T extends { createdAt: number }>(items: T[]): T[] {
  return items.sort((a, b) => a.createdAt - b.createdAt);
}

export class InMemoryBoardRepository implements BoardRepository {
  private boards = new Map<string, Board>();
  private participants = new Map<string, Participant>();
  private elements = new Map<string, Element>();
  private pins = new Map<string, Pin>();
  private scenes = new Map<string, Scene>();
  private events = new Map<string, BoardEvent[]>();
  private reclaimAttempts = new Map<string, ReclaimAttemptState>();
  private joinAttempts = new Map<string, JoinAttemptState>();
  private eventSeq = 0;

  private requireBoard(slug: string): Board {
    const board = this.boards.get(slug);
    if (!board) throw new RangeError(`Board ${slug} not found`);
    return board;
  }

  private adjustCounters(slug: string, delta: Partial<Record<keyof BoardCounters, number>>): void {
    const board = this.requireBoard(slug);
    const counters = { ...board.counters };
    for (const key of Object.keys(delta) as (keyof BoardCounters)[]) {
      counters[key] += delta[key] ?? 0;
    }
    this.boards.set(slug, { ...board, counters });
  }

  private emit(event: Omit<BoardEvent, "id">): void {
    const list = this.events.get(event.boardId) ?? [];
    list.push({ ...clone(event), id: `evt-${++this.eventSeq}` });
    this.events.set(event.boardId, list);
  }

  async createBoard(board: Board): Promise<void> {
    if (this.boards.has(board.slug)) throw new RangeError(`Board ${board.slug} already exists`);
    this.boards.set(board.slug, clone(board));
  }

  async getBoard(slug: string): Promise<Board | null> {
    const board = this.boards.get(slug);
    return board ? clone(board) : null;
  }

  // Cap check and insert share one synchronous body: no awaits
  // between them, so the cap cannot be raced in-process (PIN-91).
  private storeParticipant(participant: Participant, cap: number | null): boolean {
    const board = this.requireBoard(participant.boardId);
    const key = `${participant.boardId}/${participant.id}`;
    const isNew = !this.participants.has(key);
    if (isNew && cap !== null && board.counters.participantCount >= cap) {
      return false;
    }
    this.participants.set(key, clone(participant));
    if (isNew) {
      this.adjustCounters(participant.boardId, { participantCount: 1 });
      this.emit({
        boardId: participant.boardId,
        type: "participant_joined",
        actorId: participant.id,
        createdAt: participant.createdAt,
      });
    }
    return true;
  }

  async putParticipant(participant: Participant): Promise<void> {
    this.storeParticipant(participant, null);
  }

  async createParticipantIfBelowCap(
    participant: Participant,
    cap: number,
  ): Promise<boolean> {
    return this.storeParticipant(participant, cap);
  }

  // No awaits between read and write: atomic in-process.
  async tryRecordJoin(
    boardId: string,
    key: string,
    now: number,
    params: JoinRateParams,
  ): Promise<boolean> {
    this.requireBoard(boardId);
    const mapKey = `${boardId}/${key}`;
    const current = this.joinAttempts.get(mapKey) ?? null;
    const decision = decideJoin(boardId, key, current ? clone(current) : null, now, params);
    if (!decision.allowed || decision.next === null) return false;
    this.joinAttempts.set(mapKey, clone(decision.next));
    return true;
  }

  async getParticipant(boardId: string, participantId: string): Promise<Participant | null> {
    const participant = this.participants.get(`${boardId}/${participantId}`);
    return participant ? clone(participant) : null;
  }

  async listParticipants(boardId: string): Promise<Participant[]> {
    return byCreatedAt(
      [...this.participants.values()].filter((p) => p.boardId === boardId).map(clone),
    );
  }

  async getReclaimAttempt(
    boardId: string,
    key: string,
  ): Promise<ReclaimAttemptState | null> {
    const state = this.reclaimAttempts.get(`${boardId}/${key}`);
    return state ? clone(state) : null;
  }

  // No awaits between read and write: atomic in-process.
  async mutateReclaimAttempt(
    boardId: string,
    key: string,
    fn: (current: ReclaimAttemptState | null) => ReclaimAttemptState | null,
  ): Promise<ReclaimAttemptState | null> {
    this.requireBoard(boardId);
    const mapKey = `${boardId}/${key}`;
    const current = this.reclaimAttempts.get(mapKey) ?? null;
    const next = fn(current ? clone(current) : null);
    if (next === null) {
      this.reclaimAttempts.delete(mapKey);
      return null;
    }
    if (next.boardId !== boardId || next.key !== key) {
      throw new RangeError(`Reclaim attempt key mismatch for board ${boardId}`);
    }
    this.reclaimAttempts.set(mapKey, clone(next));
    return clone(next);
  }

  async createElement(element: Element): Promise<void> {
    this.requireBoard(element.boardId);
    if (this.elements.has(element.id)) {
      throw new RangeError(`Element ${element.id} already exists`);
    }
    this.elements.set(element.id, clone(element));
    this.adjustCounters(element.boardId, { elementCount: 1 });
    this.emit({
      boardId: element.boardId,
      type: "element_added",
      actorId: element.ownerId,
      elementId: element.id,
      createdAt: element.createdAt,
    });
  }

  async getElement(elementId: string): Promise<Element | null> {
    const element = this.elements.get(elementId);
    return element ? clone(element) : null;
  }

  async listElements(boardId: string): Promise<Element[]> {
    return byCreatedAt(
      [...this.elements.values()].filter((e) => e.boardId === boardId).map(clone),
    );
  }

  async listElementsByOwner(boardId: string, ownerId: string): Promise<Element[]> {
    return byCreatedAt(
      [...this.elements.values()]
        .filter((e) => e.boardId === boardId && e.ownerId === ownerId)
        .map(clone),
    );
  }

  // No awaits between reads and writes: atomic in-process.
  async listElementsByCutoutRef(cutoutRef: string): Promise<Element[]> {
    return byCreatedAt(
      [...this.elements.values()]
        .filter((e) => e.cutoutRef === cutoutRef)
        .map(clone),
    );
  }

  async listElementsBySource(sourceElementId: string): Promise<Element[]> {
    return byCreatedAt(
      [...this.elements.values()]
        .filter((e) => e.sourceElementId === sourceElementId)
        .map(clone),
    );
  }

  async deleteElement(elementId: string): Promise<DeleteElementResult> {
    const element = this.elements.get(elementId);
    if (!element) return { deleted: false, removedPinIds: [], hiddenSceneIds: [] };
    this.elements.delete(elementId);
    this.adjustCounters(element.boardId, { elementCount: -1 });

    const removedPinIds: string[] = [];
    for (const pin of [...this.pins.values()]) {
      if (pin.elementId !== elementId) continue;
      this.pins.delete(pin.id);
      removedPinIds.push(pin.id);
      if (pin.status === "pinned") this.adjustCounters(pin.boardId, { pinCount: -1 });
    }

    const hiddenSceneIds: string[] = [];
    for (const scene of [...this.scenes.values()]) {
      if (scene.hidden || !scene.elementIds.includes(elementId)) continue;
      this.scenes.set(scene.id, { ...clone(scene), hidden: true });
      hiddenSceneIds.push(scene.id);
      this.adjustCounters(scene.boardId, { sceneCount: -1 });
    }
    return { deleted: true, removedPinIds, hiddenSceneIds };
  }

  async createPin(pin: Pin): Promise<void> {
    this.requireBoard(pin.boardId);
    if (this.pins.has(pin.id)) throw new RangeError(`Pin ${pin.id} already exists`);
    const element = this.elements.get(pin.elementId);
    if (!element || element.boardId !== pin.boardId) {
      throw new RangeError(`Element ${pin.elementId} not found on board ${pin.boardId}`);
    }
    for (const existing of this.pins.values()) {
      if (existing.boardId === pin.boardId && existing.elementId === pin.elementId) {
        throw new RangeError(`Element ${pin.elementId} is already pinned on board ${pin.boardId}`);
      }
    }
    this.pins.set(pin.id, clone(pin));
    if (pin.status === "pinned") {
      this.adjustCounters(pin.boardId, { pinCount: 1 });
      this.emitPinAdded(pin, pin.createdAt);
    }
  }

  private emitPinAdded(pin: Pin, at: number): void {
    this.emit({
      boardId: pin.boardId,
      type: "pin_added",
      actorId: pin.pinnedBy,
      elementId: pin.elementId,
      pinId: pin.id,
      createdAt: at,
    });
  }

  async getPin(pinId: string): Promise<Pin | null> {
    const pin = this.pins.get(pinId);
    return pin ? clone(pin) : null;
  }

  async listPins(boardId: string, status?: PinStatus): Promise<Pin[]> {
    return byCreatedAt(
      [...this.pins.values()]
        .filter((p) => p.boardId === boardId && (status === undefined || p.status === status))
        .map(clone),
    );
  }

  async listPinsForElement(elementId: string): Promise<Pin[]> {
    return byCreatedAt(
      [...this.pins.values()].filter((p) => p.elementId === elementId).map(clone),
    );
  }

  async setPinStatus(pinId: string, status: PinStatus, now: number): Promise<Pin | null> {
    const pin = this.pins.get(pinId);
    if (!pin) return null;
    if (pin.status === status) return clone(pin);
    const updated: Pin = { ...clone(pin), status };
    this.pins.set(pinId, updated);
    if (status === "pinned") {
      this.adjustCounters(pin.boardId, { pinCount: 1 });
      this.emitPinAdded(updated, now);
    } else {
      this.adjustCounters(pin.boardId, { pinCount: -1 });
    }
    return clone(updated);
  }

  async deletePin(pinId: string): Promise<boolean> {
    const pin = this.pins.get(pinId);
    if (!pin) return false;
    this.pins.delete(pinId);
    if (pin.status === "pinned") this.adjustCounters(pin.boardId, { pinCount: -1 });
    return true;
  }

  async putScene(scene: Scene): Promise<void> {
    this.requireBoard(scene.boardId);
    const before = this.scenes.get(scene.id);
    if (before && before.boardId !== scene.boardId) {
      throw new RangeError(`Scene ${scene.id} belongs to board ${before.boardId}`);
    }
    const wasVisible = before ? !before.hidden : false;
    const isVisible = !scene.hidden;
    this.scenes.set(scene.id, clone(scene));
    const delta = Number(isVisible) - Number(wasVisible);
    if (delta !== 0) this.adjustCounters(scene.boardId, { sceneCount: delta });
  }

  async getScene(sceneId: string): Promise<Scene | null> {
    const scene = this.scenes.get(sceneId);
    return scene ? clone(scene) : null;
  }

  async listScenes(boardId: string, opts?: { includeHidden?: boolean }): Promise<Scene[]> {
    return byCreatedAt(
      [...this.scenes.values()]
        .filter((s) => s.boardId === boardId && (opts?.includeHidden || !s.hidden))
        .map(clone),
    );
  }

  async appendEvent(event: BoardEvent): Promise<void> {
    this.requireBoard(event.boardId);
    const list = this.events.get(event.boardId) ?? [];
    if (list.some((e) => e.id === event.id)) {
      throw new RangeError(`Event ${event.id} already exists on board ${event.boardId}`);
    }
    list.push(clone(event));
    this.events.set(event.boardId, list);
  }

  async listEvents(boardId: string, opts?: { limit?: number }): Promise<BoardEvent[]> {
    const all = byCreatedAt((this.events.get(boardId) ?? []).map(clone));
    if (opts?.limit === undefined) return all;
    if (opts.limit <= 0) return [];
    return all.slice(-opts.limit);
  }
}
